"""Browser playthrough for Gangs of Lagos. Needs: pip install playwright; a running build (npm run build && npm run preview).
Set GOL_URL to point elsewhere (default http://localhost:4173/?debug)."""
import asyncio, json, sys
from playwright.async_api import async_playwright
import os
URL=os.environ.get('GOL_URL','http://localhost:4173/?debug')
SHOTS=sys.argv[1] if len(sys.argv)>1 else ''
fails=[]
def ok(name,cond,extra=''):
    if not cond: fails.append(name)
    print(("PASS " if cond else "FAIL ")+name+(" "+str(extra) if extra else ""), flush=True)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
        pg=await b.new_page(viewport={'width':960,'height':540})
        errs=[]
        pg.on('pageerror',lambda e:errs.append('PAGEERROR '+str(e)))
        pg.on('console',lambda m:errs.append(m.text) if m.type=='error' and 'fonts.g' not in m.text and 'TUNNEL' not in m.text and 'ERR_FAILED' not in m.text else None)
        await pg.route(lambda u: 'fonts.g' in u, lambda r: r.abort())
        E=pg.evaluate
        async def sim(s): await E(f'__gol.simulate({s})')
        async def txt(i): return await E(f"document.getElementById('{i}').textContent")
        async def hidden(i): return await E(f"document.getElementById('{i}').hidden")
        async def shot(n):
            if SHOTS: await pg.screenshot(path=f'{SHOTS}/{n}.png')
        async def key(k): await pg.keyboard.press(k); await sim(0.1)
        await pg.goto(URL)
        await E('localStorage.clear()'); await pg.reload()
        await pg.wait_for_function("!document.getElementById('btn-play').disabled",timeout=90000)
        ok('title shown', await E("__gol.mode")=='title', await txt('save-note'))
        await shot('t_title')
        await pg.click('#btn-play'); await pg.wait_for_timeout(500)
        if await E('__gol.mode')=='wardrobe': await pg.click('#btn-wdone'); await pg.wait_for_timeout(200)
        ok('playing', await E("__gol.mode")=='play')
        await pg.focus('#game')
        ok('traffic on the roads', await E("__gol.traffic.activeCount")>=6, await E("__gol.traffic.activeCount"))
        ok('start: nothing inside buildings', not any((await E("__gol.overlapping()")).values()), await E("__gol.overlapping()"))
        await sim(0.1)
        ok('compass points to first job giver', not await hidden('compass'), await txt('c-dist'))
        # Locked givers
        await E("__gol.approach('Emeka')"); await sim(0.1); await key('KeyE')
        sub=await txt('subtitle'); ok('Emeka job locked at first', 'Mama Titi' in sub and await E("__gol.mode")=='play', sub)
        await E("__gol.approach('Mama Titi')"); await sim(0.1); await key('KeyE')
        sub=await txt('subtitle'); ok('Mama Titi job locked at first', 'race' in sub, sub)
        # ---- Job 1: race
        await E("__gol.approach('Kunle')"); await sim(0.1)
        pr=await txt('prompt'); ok('prompt offers job', 'about a job' in pr, pr)
        await key('KeyE')
        ok('offer card', await E("__gol.mode")=='offer', await txt('o-terms'))
        await shot('t_offer')
        await pg.click('#btn-accept'); await sim(0.1)
        m=await E("__gol.mission"); ok('race accepted', m['state']=='active' and m['step']=='enter', m)
        await E("__gol.teleportPlayer(__gol.hatch.x+2.2,__gol.hatch.z)"); await sim(0.1); await key('KeyE')
        ok('enter car', await E("__gol.inVehicle")=='hatchback')
        await sim(0.1)
        m=await E("__gol.mission"); ok('race: drive to start', m['step']=='goto' and not m['timerOn'], m)
        await E("__gol.teleportVehicle(__gol.hatch,-40,-4,Math.PI/2)"); await sim(0.4)
        m=await E("__gol.mission"); ok('race countdown', m['step']=='countdown', m)
        await sim(3.3)
        m=await E("__gol.mission"); ok('race active, timer on', m['step']=='goto' and m['timerOn'], m)
        await shot('t_race')
        for (x,z) in [(-40,40),(40,40),(120,40),(120,-120),(-40,-120),(-40,-40)]:
            await E(f"__gol.teleportVehicle(__gol.hatch,{x},{z})"); await sim(0.15)
        s=await E("__gol.save"); m=await E("__gol.mission")
        ok('race complete + reward', m['state']=='result' and s['cash']==5000 and 'danfo' in s['paints']['owned'] and s['paints']['active']=='danfo', {'cash':s['cash'],'paints':s['paints']})
        ok('result card', 'RACE COMPLETE' in await txt('r-title'), await txt('r-body'))
        await pg.click('#btn-continue'); await sim(0.1)
        # pause jobs list
        await key('KeyP')
        jobs=await txt('pause-jobs'); ok('pause lists jobs', 'Market Run' in jobs and 'Done' in jobs and 'Locked' in jobs, jobs[:160])
        await shot('t_pause')
        await pg.click('#btn-resume'); await sim(0.1)
        # ---- Job 2: delivery
        await E("__gol.leaveVehicle()")
        await E("__gol.approach('Mama Titi')"); await sim(0.1); await key('KeyE')
        ok('market run offered', await E("__gol.mode")=='offer')
        await pg.click('#btn-accept'); await sim(0.1)
        await E("__gol.teleportPlayer(-74,61)"); await sim(0.3)
        m=await E("__gol.mission"); ok('parcel collected on foot', m['cargo']==100 and m['step']=='enter', m)
        await E("__gol.teleportVehicle(__gol.hatch,-40,-60,Math.PI)"); await E("__gol.teleportPlayer(-40,-57.9)"); await sim(0.1); await key('KeyE')
        ok('in car with parcel, timer on', (await E("__gol.mission"))['timerOn'] and await E("__gol.inVehicle")=='hatchback')
        await pg.keyboard.down('KeyW'); await sim(2.0); await pg.keyboard.up('KeyW'); await sim(0.3)
        m=await E("__gol.mission"); h=await E("__gol.hatch.healthPct")
        ok('crash damages parcel and car', m['cargo']<100 and h<1, {'cargo':m['cargo'],'car':h})
        await E("__gol.teleportVehicle(__gol.hatch,123,-150,Math.PI/2)"); await sim(0.3)
        s=await E("__gol.save"); body=await txt('r-body')
        ok('delivered, pay scaled by damage', (await E("__gol.mission"))['state']=='result' and 'Parcel condition' in body and 5000< s['cash'] < 9000, body)
        await pg.click('#btn-continue'); await sim(0.1)
        # ---- Job 3: danfo shift
        await E("__gol.leaveVehicle()")
        await E("__gol.approach('Emeka')"); await sim(0.1); await key('KeyE')
        ok('danfo shift offered', await E("__gol.mode")=='offer')
        await pg.click('#btn-accept'); await sim(0.1)
        await E("__gol.teleportPlayer(__gol.hatch.x+2.4,__gol.hatch.z)"); await sim(0.1); await key('KeyE'); await sim(0.2)
        ok('hatchback does not count for the shift', (await E("__gol.mission"))['step']=='enter')
        await E("__gol.leaveVehicle()")
        await E("__gol.teleportPlayer(__gol.danfo.x+2.4,__gol.danfo.z)"); await sim(0.1); await key('KeyE'); await sim(0.2)
        ok('in the danfo', await E("__gol.inVehicle")=='danfo', await E("__gol.mission"))
        await shot('t_danfo')
        stops=[(0,43,0),(-43,80,-1.5708),(0,-37,0),(123,-30,-1.5708),(100,37,3.1416),(0,43,3.1416)]
        for i,(x,z,hd) in enumerate(stops):
            await E(f"__gol.teleportVehicle(__gol.danfo,{x},{z},{hd})"); await sim(0.6)
            if i==1:
                o=await txt('m-obj'); ok('bus stop needs a held stop', '(' in o, o)
            await sim(1.8)
        m=await E("__gol.mission"); s=await E("__gol.save")
        ok('shift done with fares', m['state']=='result' and 'Fares' in await txt('r-body'), await txt('r-body'))
        ok('finale granted', not await hidden('r-finale') and 1 in s['chaptersDone'] and 'gold' in s['paints']['owned'], await txt('r-finale'))
        await shot('t_finale')
        await pg.click('#btn-continue'); await sim(0.1)
        cash_before=s['cash']
        # ---- Workshop
        await E("__gol.leaveVehicle()")
        await E("__gol.hatch.health=50"); await E("__gol.teleportVehicle(__gol.hatch,45,0,0)")
        await E("__gol.teleportPlayer(45,2.1)"); await sim(0.1); await key('KeyE')
        await E("__gol.teleportVehicle(__gol.hatch,57,0,0)"); await sim(0.2)
        ok('shop opens in the bay', await E("__gol.mode")=='shop', await txt('shop-vehicle'))
        rep=await txt('btn-repair'); ok('repair priced', '1,000' in rep, rep)
        await shot('t_shop')
        await pg.click('#btn-repair')
        s=await E("__gol.save"); ok('repair works', await E("__gol.hatch.healthPct")==1 and s['cash']==cash_before-1000, s['cash'])
        await pg.click('button[data-paint="blue"]')
        s=await E("__gol.save"); ok('buy paint', 'blue' in s['paints']['owned'] and s['paints']['active']=='blue' and s['cash']==cash_before-3500)
        await pg.click('button[data-paint="gold"]')
        ok('apply earned paint', (await E("__gol.save"))['paints']['active']=='gold')
        await pg.click('#btn-leave'); await sim(0.1)
        ok('leave shop', await E("__gol.mode")=='play')
        # ---- Wreck: the car catches fire (no tow); get out, it burns out, your car is rebuilt at the workshop
        await E("__gol.hatch.health=2"); await E("__gol.teleportVehicle(__gol.hatch,-40,-60,Math.PI)")
        await pg.keyboard.down('KeyW'); await sim(2.0); await pg.keyboard.up('KeyW'); await sim(0.2)
        ok('wrecked car catches fire instead of being towed', await E("__gol.fires.has(__gol.hatch)") and (await E("__gol.save"))['stats']['tows']==0, await txt('notice'))
        await key('KeyE'); await sim(8)
        ok('burnt-out car disappears once you are out', await E("__gol.inVehicle") is None and not await E("__gol.hatch.group.visible") and await E("__gol.mode")=='play')
        await sim(31)
        hx=await E("[__gol.hatch.x,__gol.hatch.z]")
        ok('your car is rebuilt at the workshop', abs(hx[0]-66)<0.1 and abs(hx[1]+14)<0.1 and await E("__gol.hatch.healthPct")==1 and await E("__gol.hatch.group.visible"), hx)
        # ---- Map
        await key('KeyM'); ok('full map opens', await E("__gol.mode")=='map')
        await shot('t_map')
        await key('KeyM'); ok('full map closes', await E("__gol.mode")=='play')
        # ---- Horn scatters residents
        await E("__gol.approach('Baba Sule')"); await E("(()=>{const r=__gol.residents.find(r=>r.name==='Baba Sule');__gol.teleportVehicle(__gol.hatch,r.x-6,r.z,0);})()")
        await E("__gol.enterVehicle(__gol.hatch)"); await key('KeyH')
        ok('horn scatters residents', await E("__gol.residents.find(r=>r.name==='Baba Sule').fleeTimer")>0)
        # ---- Traffic drives and never ends up inside buildings
        p0=await E("__gol.traffic.vehicles().map(v=>[v.x,v.z])")
        await sim(8)
        p1=await E("__gol.traffic.vehicles().map(v=>[v.x,v.z])")
        bad=await E("__gol.traffic.vehicles().filter(v=>__gol.overlapping && false).length")
        inside=await E("""(()=>{let n=0; for(const v of __gol.traffic.vehicles()){ const w=Math.abs(((v.x%80)+80)%80-40)<9 || Math.abs(((v.z%80)+80)%80-40)<9; if(!w) n++;} return n})()""")
        moved=sum(1 for a,b2 in zip(p0,p1) if ((a[0]-b2[0])**2+(a[1]-b2[1])**2)**.5>5)
        ok('traffic moves along roads', moved>=3 and inside==0, {'moved':moved,'offroad':inside,'n':len(p1),'mode':await E('__gol.mode'),'m':await E('__gol.mission'),'scr':await E("[...document.querySelectorAll('section.screen')].filter(e=>!e.hidden).map(e=>e.id)")})
        # ---- Fail path: leaving the car during the race
        await E("__gol.leaveVehicle()")
        await E("__gol.approach('Kunle')"); await sim(0.1); await key('KeyE'); await pg.click('#btn-accept'); await sim(0.1)
        await E("__gol.teleportPlayer(__gol.hatch.x+2.2,__gol.hatch.z)"); await sim(0.1); await key('KeyE')
        await E("__gol.teleportVehicle(__gol.hatch,-40,-4,Math.PI/2)"); await sim(4.0)
        await key('KeyE')
        ok('leaving the car does not cancel the job any more', (await E("__gol.mission"))['state']=='active' and await E("__gol.inVehicle") is None, await E("__gol.mission"))
        await E("__gol.runner().fail('test: end the race')"); await sim(0.1)
        # retry puts the car on the line
        await E("__gol.teleportPlayer(__gol.hatch.x+2.2,__gol.hatch.z)")
        await pg.click('#btn-continue'); await sim(0.1)
        # ---- Persistence + migration
        await E("__gol.leaveVehicle()")
        await key('KeyP'); await pg.click('#btn-title')
        await pg.reload(); await pg.wait_for_function("!document.getElementById('btn-play').disabled",timeout=90000)
        s=await E("__gol.save")
        ok('save persists', 1 in s['chaptersDone'] and s['paints']['active']=='gold' and len(s['completedMissions'])==3 and s['lookChosen'], {'cash':s['cash']})
        await E("""localStorage.setItem('gangs-of-lagos/save', JSON.stringify({version:1,cash:5500,completedMissions:['harbour-sprint'],unlocks:['paint-danfo'],bestTimes:{'harbour-sprint':61.2},settings:{masterVolume:0.5,lookSensitivity:1.3,invertY:false}}))""")
        await pg.reload(); await pg.wait_for_function("!document.getElementById('btn-play').disabled",timeout=90000)
        s=await E("__gol.save")
        ok('v1 save migrates', s['version']==5 and s['cash']==5500 and s['paints']=={'owned':['green','danfo'],'active':'danfo'} and s['settings']['lookSensitivity']==1.3 and 'unlocks' not in s and s['chaptersDone']==[] and s['lookChosen']==False, s)
        ok('migration noted on title', 'upgraded' in await txt('save-note'), await txt('save-note'))
        print('ERRORS', errs[:8])
        print('FAILED:', fails)
        await b.close()
asyncio.run(main())
